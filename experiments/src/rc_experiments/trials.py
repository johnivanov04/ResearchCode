"""Trial identifiers, the randomised schedule, and trial records.

A trial is one agent session on one task under one condition. Its identifier is
``<task>--<condition>--<replicate>`` where the replicate is ``pNN`` for pilot trials and
``rNN`` for confirmatory trials. Trial records (``trial.json``) live next to the
workspace, never inside it, so the agent cannot see them.
"""

from __future__ import annotations

import json
import random
from dataclasses import asdict, dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from rc_experiments.config import Config

DATA_KINDS = ("genuine", "pilot", "fixture")


@dataclass(frozen=True)
class TrialId:
    task: str
    condition: str
    replicate: str  # "p01" (pilot) or "r01" (confirmatory)

    def __str__(self) -> str:
        return f"{self.task}--{self.condition}--{self.replicate}"

    @classmethod
    def parse(cls, text: str) -> TrialId:
        parts = text.split("--")
        if len(parts) != 3 or parts[2][:1] not in ("p", "r") or not parts[2][1:].isdigit():
            raise ValueError(f"invalid trial id {text!r}; expected <task>--<condition>--<pNN|rNN>")
        return cls(*parts)

    @property
    def is_pilot(self) -> bool:
        return self.replicate.startswith("p")


@dataclass(frozen=True)
class ScheduledTrial:
    order: int
    block: int
    phase: str  # "pilot" or "confirmatory"
    trial_id: str


def make_schedule(config: Config) -> list[ScheduledTrial]:
    """Blocked randomisation: each block holds every task x condition once, in random order.

    Block 0 is the pilot (excluded from analysis); blocks 1..N are confirmatory. The order
    depends only on the seed in ``experiment.json``.
    """
    rng = random.Random(config.design["schedule_seed"])  # noqa: S311 - reproducible ordering, not security
    cells = [(task, condition) for task in config.task_ids for condition in config.condition_ids]
    schedule: list[ScheduledTrial] = []
    plan = [("pilot", "p", r) for r in range(1, config.design["pilot_trials_per_cell"] + 1)]
    plan += [("confirmatory", "r", r) for r in range(1, config.design["confirmatory_trials_per_cell"] + 1)]
    for block, (phase, prefix, replicate) in enumerate(plan):
        block_cells = cells[:]
        rng.shuffle(block_cells)
        for task, condition in block_cells:
            trial = TrialId(task, condition, f"{prefix}{replicate:02d}")
            schedule.append(ScheduledTrial(len(schedule) + 1, block, phase, str(trial)))
    return schedule


def schedule_document(config: Config) -> dict[str, Any]:
    return {
        "protocol_version": config.protocol_version,
        "seed": config.design["schedule_seed"],
        "note": "Generated by `rc-exp schedule --write` from experiment.json. Run trials in this order.",
        "trials": [asdict(t) for t in make_schedule(config)],
    }


def now_utc() -> str:
    return datetime.now(UTC).isoformat(timespec="seconds")


def read_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def write_json(path: Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, sort_keys=False, allow_nan=True) + "\n", encoding="utf-8")


def update_record(trial_dir: Path, **fields: Any) -> dict[str, Any]:
    path = trial_dir / "trial.json"
    record = read_json(path) if path.is_file() else {}
    record.update(fields)
    write_json(path, record)
    return record
